package com.israrxy.raazi.data.remote

import com.israrxy.raazi.ui.cleanBracketedText
import com.israrxy.raazi.ui.parseLrcLines
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

class NewPipeCaptionLyricsExtractorTest {

    private val extractor = NewPipeCaptionLyricsExtractor()

    @Test
    fun parseWebVttToLrc_stripsNoiseAndFormatsTimestamps() {
        val vtt = """
            WEBVTT
            Kind: captions
            Language: en

            00:00:01.200 --> 00:00:03.500
            [Music]

            00:00:03.500 --> 00:00:07.100
            I've been on my own for long enough

            00:00:07.100 --> 00:00:11.450
            Maybe you can show me how to love, <b>maybe</b>

            00:00:11.450 --> 00:00:15.000
            ♪ I'm going through withdrawals ♪
        """.trimIndent()

        val lrc = extractor.parseCaptionsToLrc(vtt)
        assertNotNull(lrc)

        val pairs = parseLrcLines(lrc!!)
        assertEquals(3, pairs.size)
        assertEquals("I've been on my own for long enough", pairs[0].second)
        assertEquals(3_500L, pairs[0].first)

        assertEquals("Maybe you can show me how to love, maybe", pairs[1].second)
        assertEquals(7_100L, pairs[1].first)

        assertEquals("I'm going through withdrawals", pairs[2].second)
        assertEquals(11_450L, pairs[2].first)
    }

    @Test
    fun parseXmlTranscriptToLrc_handlesNumericTimestamps() {
        val xml = """
            <transcript>
                <text start="2.45" dur="3.1">First lyric line</text>
                <text start="5.8" dur="4.0">Second lyric line with &amp; entity</text>
                <text start="10.12" dur="2.0">[Applause]</text>
                <text start="12.5" dur="3.0">Third lyric line</text>
            </transcript>
        """.trimIndent()

        val lrc = extractor.parseCaptionsToLrc(xml)
        assertNotNull(lrc)

        val pairs = parseLrcLines(lrc!!)
        assertEquals(3, pairs.size)
        assertEquals("First lyric line", pairs[0].second)
        assertEquals(2_450L, pairs[0].first)

        assertEquals("Second lyric line with & entity", pairs[1].second)
        assertEquals(5_800L, pairs[1].first)

        assertEquals("Third lyric line", pairs[2].second)
        assertEquals(12_500L, pairs[2].first)
    }

    @Test
    fun parseXmlFormat3ToLrc_handlesMillisecondTimestampsAndInnerTags() {
        val xml = """
            <?xml version="1.0" encoding="utf-8" ?>
            <timedtext format="3">
            <body>
            <p t="1360" d="1680">[♪♪♪]</p>
            <p t="18640" d="3240">♪ We&#39;re no strangers to love ♪</p>
            <p t="22640" d="4320"><s>You know the rules</s> <s>and so do I</s></p>
            <p t="27080" d="4120">A full commitment&#39;s what I&#39;m thinkin&#39; of</p>
            </body>
            </timedtext>
        """.trimIndent()

        val lrc = extractor.parseCaptionsToLrc(xml)
        assertNotNull(lrc)

        val pairs = parseLrcLines(lrc!!)
        assertEquals(3, pairs.size)
        assertEquals("We're no strangers to love", pairs[0].second)
        assertEquals(18_640L, pairs[0].first)

        assertEquals("You know the rules and so do I", pairs[1].second)
        assertEquals(22_640L, pairs[1].first)

        assertEquals("A full commitment's what I'm thinkin' of", pairs[2].second)
        assertEquals(27_080L, pairs[2].first)
    }

    @Test
    fun parseJson3ToLrc_handlesEventsAndSegments() {
        val json = """
            {
              "wireMagic": "pb3",
              "events": [
                {
                  "tStartMs": 1500,
                  "dDurationMs": 2000,
                  "segs": [
                    { "utf8": "Hello " },
                    { "utf8": "world" }
                  ]
                },
                {
                  "tStartMs": 4000,
                  "dDurationMs": 3000,
                  "segs": [
                    { "utf8": "Never gonna give you up" }
                  ]
                },
                {
                  "tStartMs": 8000,
                  "dDurationMs": 2000,
                  "segs": [
                    { "utf8": "♪" }
                  ]
                }
              ]
            }
        """.trimIndent()

        val lrc = extractor.parseCaptionsToLrc(json)
        assertNotNull(lrc)

        val pairs = parseLrcLines(lrc!!)
        assertEquals(2, pairs.size)
        assertEquals("Hello world", pairs[0].second)
        assertEquals(1_500L, pairs[0].first)

        assertEquals("Never gonna give you up", pairs[1].second)
        assertEquals(4_000L, pairs[1].first)
    }

    @Test
    fun selectBestSubtitleTrack_prioritizesHumanOverAutoAndLanguage() {
        val tracks = listOf(
            CaptionTrackInfo("url1", "en", "English (auto-generated)", isAutoGenerated = true),
            CaptionTrackInfo("url2", "es", "Spanish", isAutoGenerated = false),
            CaptionTrackInfo("url3", "en", "English", isAutoGenerated = false)
        )

        val best = extractor.selectBestSubtitleTrack(tracks, preferredLanguage = null)
        assertNotNull(best)
        assertEquals("url3", best!!.url)
        assertEquals(false, best.isAutoGenerated)

        val bestSpanish = extractor.selectBestSubtitleTrack(tracks, preferredLanguage = "es")
        assertNotNull(bestSpanish)
        assertEquals("url2", bestSpanish!!.url)
    }

    @Test
    fun cleanBracketedText_stripsSquareBracketsAndExtraWhitespace() {
        assertEquals("Never gonna give you up", cleanBracketedText("Never gonna give you up [Never gonna give]"))
        assertEquals("", cleanBracketedText("[Chorus]"))
        assertEquals("Some actual lyrics", cleanBracketedText("[Music] Some actual lyrics [applause]"))
        assertEquals("Normal line", cleanBracketedText("Normal line"))
    }

    @Test
    fun parseLrcLines_withHideBrackets_dropsPureBracketLinesAndCleansLyrics() {
        val lrc = """
            [00:01.00][Intro]
            [00:05.00]Never gonna give you up [Never gonna give]
            [00:10.00][Chorus]
            [00:15.00]Never gonna let you down
        """.trimIndent()

        val pairs = parseLrcLines(lrc, hideBrackets = true)
        assertEquals(2, pairs.size)
        assertEquals(5_000L, pairs[0].first)
        assertEquals("Never gonna give you up", pairs[0].second)
        assertEquals(15_000L, pairs[1].first)
        assertEquals("Never gonna let you down", pairs[1].second)

        val pairsAll = parseLrcLines(lrc, hideBrackets = false)
        assertEquals(4, pairsAll.size)
    }
}
