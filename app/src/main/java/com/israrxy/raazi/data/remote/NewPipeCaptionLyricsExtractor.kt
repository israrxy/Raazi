package com.israrxy.raazi.data.remote

import android.util.Log
import com.google.gson.JsonParser
import com.israrxy.raazi.player.StreamResolver
import com.israrxy.raazi.service.YouTubeMusicExtractor
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import okhttp3.OkHttpClient
import okhttp3.Request
import org.json.JSONObject
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.util.Locale
import java.util.concurrent.TimeUnit

class NewPipeCaptionLyricsExtractor(
    private val client: OkHttpClient = OkHttpClient.Builder()
        .connectTimeout(5, TimeUnit.SECONDS)
        .readTimeout(5, TimeUnit.SECONDS)
        .followRedirects(true)
        .build()
) {
    private val tag = "NewPipeCaptions"

    suspend fun fetchCaptionsAsLyrics(
        videoId: String,
        trackName: String,
        artistName: String,
        durationSeconds: Double,
        preferredLanguage: String? = null
    ): Lyrics? = withContext(Dispatchers.IO) {
        withTimeoutOrNull(4500L) {
            runCatching {
                val cleanId = extractCleanVideoId(videoId) ?: return@runCatching null

                // Ensure NewPipe is initialized
                YouTubeMusicExtractor.getInstance()

                // Check stream cache first, or fetch from NewPipe
                val streamInfo = StreamResolver.getCachedStreamInfo(cleanId) ?: run {
                    val url = "https://www.youtube.com/watch?v=$cleanId"
                    StreamInfo.getInfo(ServiceList.YouTube, url)
                }

                val subtitles = streamInfo.subtitles
                if (subtitles.isNullOrEmpty()) {
                    Log.d(tag, "No subtitle/caption streams found for $cleanId")
                    return@runCatching null
                }

                val bestTrack = selectBestSubtitleTrack(subtitles, preferredLanguage)
                    ?: return@runCatching null

                Log.d(
                    tag,
                    "Extracting captions [lang=${bestTrack.languageTag}, auto=${bestTrack.isAutoGenerated}] for $cleanId"
                )

                val rawContent = downloadSubtitleContent(bestTrack)
                if (rawContent.isNullOrBlank()) {
                    Log.w(tag, "Downloaded subtitle content was empty for $cleanId")
                    return@runCatching null
                }

                val lrc = parseCaptionsToLrc(rawContent)
                if (lrc.isNullOrBlank() || !isValidLrcTranscript(lrc)) {
                    Log.d(tag, "Parsed caption text was not valid LRC for $cleanId")
                    return@runCatching null
                }

                val plain = stripLrcTags(lrc)
                if (plain.isBlank() || plain.length < 20) return@runCatching null

                val isAuto = bestTrack.isAutoGenerated
                Lyrics(
                    id = "$cleanId|NewPipeCaptions".hashCode(),
                    trackName = trackName,
                    artistName = artistName,
                    plainLyrics = plain,
                    syncedLyrics = lrc,
                    duration = durationSeconds,
                    language = bestTrack.languageTag,
                    source = if (isAuto) "YouTube Captions (Auto)" else "YouTube Captions"
                )
            }.getOrElse { e ->
                Log.w(tag, "Caption extraction failed for $videoId: ${e.message}")
                null
            }
        }
    }

    private fun selectBestSubtitleTrack(
        subtitles: List<SubtitlesStream>,
        preferredLanguage: String?
    ): SubtitlesStream? {
        val preferred = preferredLanguage?.lowercase()?.trim()?.takeIf { it.isNotBlank() }

        // 1. Human-uploaded (non-auto) matching preferred language
        if (preferred != null) {
            subtitles.firstOrNull {
                !it.isAutoGenerated && it.languageTag.equals(preferred, ignoreCase = true)
            }?.let { return it }
        }

        // 2. Human-uploaded English
        subtitles.firstOrNull {
            !it.isAutoGenerated && it.languageTag.startsWith("en", ignoreCase = true)
        }?.let { return it }

        // 3. Human-uploaded any language
        subtitles.firstOrNull { !it.isAutoGenerated }?.let { return it }

        // 4. Auto-generated matching preferred language
        if (preferred != null) {
            subtitles.firstOrNull {
                it.isAutoGenerated && it.languageTag.equals(preferred, ignoreCase = true)
            }?.let { return it }
        }

        // 5. Auto-generated English
        subtitles.firstOrNull {
            it.isAutoGenerated && it.languageTag.startsWith("en", ignoreCase = true)
        }?.let { return it }

        // 6. First available
        return subtitles.firstOrNull()
    }

    private fun downloadSubtitleContent(track: SubtitlesStream): String? {
        if (!track.content.isNullOrBlank()) {
            return track.content
        }
        var url = track.url ?: return null
        if (!url.contains("fmt=")) {
            url = if (url.contains("?")) "$url&fmt=vtt" else "$url?fmt=vtt"
        }

        val request = Request.Builder()
            .url(url)
            .header("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64)")
            .build()

        return client.newCall(request).execute().use { response ->
            if (response.isSuccessful) response.body?.string() else null
        }
    }

    internal fun parseCaptionsToLrc(raw: String): String? {
        val trimmed = raw.trim()
        return when {
            trimmed.startsWith("WEBVTT") || trimmed.contains("-->") -> parseVttToLrc(trimmed)
            trimmed.contains("<transcript") || trimmed.contains("<text ") -> parseXmlToLrc(trimmed)
            trimmed.startsWith("{") && trimmed.contains("\"events\"") -> parseJson3ToLrc(trimmed)
            else -> parseVttToLrc(trimmed)
        }.takeIf { it.isNotBlank() }
    }

    private fun parseVttToLrc(vttText: String): String {
        val lines = vttText.lines()
        val result = StringBuilder()
        val timeRegex = Regex("""(?:(\d{2}):)?(\d{2}):(\d{2})[.,](\d{2,3})\s*-->""")
        var prevText = ""
        var i = 0

        while (i < lines.size) {
            val line = lines[i].trim()
            val match = timeRegex.find(line)
            if (match != null) {
                val hours = match.groupValues[1].toIntOrNull() ?: 0
                val minutes = match.groupValues[2].toIntOrNull() ?: 0
                val seconds = match.groupValues[3].toIntOrNull() ?: 0
                val msStr = match.groupValues[4]
                val ms = msStr.padEnd(3, '0').take(3).toIntOrNull() ?: 0

                val totalSec = hours * 3600 + minutes * 60 + seconds
                val totalMin = totalSec / 60
                val remSec = totalSec % 60
                val centis = ms / 10

                i++
                val textBuilder = StringBuilder()
                while (i < lines.size && lines[i].isNotBlank() && !timeRegex.containsMatchIn(lines[i])) {
                    val clean = cleanCaptionText(lines[i])
                    if (clean.isNotBlank()) {
                        if (textBuilder.isNotEmpty()) textBuilder.append(" ")
                        textBuilder.append(clean)
                    }
                    i++
                }

                val text = textBuilder.toString().trim()
                if (text.isNotBlank() && text != prevText && !isNoiseCue(text)) {
                    result.append(String.format(Locale.US, "[%02d:%02d.%02d]%s\n", totalMin, remSec, centis, text))
                    prevText = text
                }
                continue
            }
            i++
        }
        return result.toString().trim()
    }

    private fun parseXmlToLrc(xmlText: String): String {
        val result = StringBuilder()
        val tagRegex = Regex("""<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>(.*?)</text>""", RegexOption.DOT_MATCHES_ALL)
        var prevText = ""

        for (match in tagRegex.findAll(xmlText)) {
            val startSec = match.groupValues[1].toDoubleOrNull() ?: continue
            val rawText = match.groupValues[3]
            val clean = cleanCaptionText(rawText)
            if (clean.isNotBlank() && clean != prevText && !isNoiseCue(clean)) {
                val timeMs = Math.round(startSec * 1000.0)
                val minutes = timeMs / 60000
                val seconds = (timeMs / 1000) % 60
                val centis = (timeMs % 1000) / 10
                result.append(String.format(Locale.US, "[%02d:%02d.%02d]%s\n", minutes, seconds, centis, clean))
                prevText = clean
            }
        }
        return result.toString().trim()
    }

    private fun parseJson3ToLrc(jsonText: String): String {
        val result = StringBuilder()
        var prevText = ""
        runCatching {
            val root = JsonParser.parseString(jsonText).asJsonObject
            val events = root.getAsJsonArray("events") ?: return@runCatching
            for (eventElement in events) {
                val event = eventElement.asJsonObject
                val startMs = if (event.has("tStartMs")) event.get("tStartMs").asLong else -1L
                if (startMs < 0) continue
                val segs = if (event.has("segs")) event.getAsJsonArray("segs") else continue
                val segText = StringBuilder()
                for (segElement in segs) {
                    val seg = segElement.asJsonObject
                    if (seg.has("utf8")) {
                        segText.append(seg.get("utf8").asString)
                    }
                }
                val clean = cleanCaptionText(segText.toString())
                if (clean.isNotBlank() && clean != prevText && !isNoiseCue(clean)) {
                    val minutes = startMs / 60000
                    val seconds = (startMs / 1000) % 60
                    val centis = (startMs % 1000) / 10
                    result.append(String.format(Locale.US, "[%02d:%02d.%02d]%s\n", minutes, seconds, centis, clean))
                    prevText = clean
                }
            }
        }
        return result.toString().trim()
    }

    private fun cleanCaptionText(raw: String): String {
        return raw
            .replace(Regex("""<[^>]+>"""), "") // Strip HTML/VTT tags
            .replace("&amp;", "&")
            .replace("&#39;", "'")
            .replace("&quot;", "\"")
            .replace("&lt;", "<")
            .replace("&gt;", ">")
            .replace("&nbsp;", " ")
            .replace("\n", " ")
            .trim('♪', ' ', '\t', '\r', '\n')
            .trim()
    }

    private fun isNoiseCue(text: String): Boolean {
        val lower = text.lowercase().trim()
        return lower in NOISE_CUES
    }

    private fun extractCleanVideoId(rawId: String?): String? {
        if (rawId.isNullOrBlank()) return null
        val stripped = rawId
            .removePrefix("youtube_")
            .substringAfter("v=", rawId.removePrefix("youtube_"))
            .substringBefore("&")
            .trim()
        return stripped.takeIf { it.length in 10..12 && !it.contains(" ") }
    }

    private fun isValidLrcTranscript(lrc: String): Boolean {
        val lines = lrc.lines().filter { it.isNotBlank() }
        if (lines.size < 3) return false
        val timestampedCount = lines.count { it.startsWith("[") && it.contains("]") }
        return timestampedCount >= 3
    }

    private fun stripLrcTags(lrc: String): String {
        val regex = Regex("""\[\d+:\d+(?:\.\d+)?\]|<\d+:\d+(?:\.\d+)?>""")
        return lrc.lineSequence()
            .map { it.replace(regex, "").trim() }
            .filter { it.isNotBlank() }
            .joinToString("\n")
    }

    companion object {
        private val NOISE_CUES = setOf(
            "[music]", "(music)", "music",
            "[applause]", "(applause)",
            "[laughter]", "(laughter)",
            "[cheering]", "(cheering)"
        )
    }
}
