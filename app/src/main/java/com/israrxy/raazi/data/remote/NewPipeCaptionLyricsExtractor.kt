package com.israrxy.raazi.data.remote

import android.util.Log
import com.google.gson.JsonElement
import com.google.gson.JsonObject
import com.google.gson.JsonParser
import com.israrxy.raazi.player.StreamResolver
import com.israrxy.raazi.service.YouTubeMusicExtractor
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.util.concurrent.TimeUnit

internal data class CaptionTrackInfo(
    val url: String,
    val languageCode: String,
    val name: String,
    val isAutoGenerated: Boolean,
    val content: String? = null
)

class NewPipeCaptionLyricsExtractor(
    private val client: OkHttpClient = OkHttpClient.Builder()
        .connectTimeout(6, TimeUnit.SECONDS)
        .readTimeout(6, TimeUnit.SECONDS)
        .followRedirects(true)
        .build()
) {
    private val tag = "NewPipeCaptions"

    suspend fun fetchCaptionsAsLyrics(
        videoId: String,
        trackName: String,
        artistName: String,
        durationSeconds: Double,
        preferredLanguage: String? = null
    ): Lyrics? = withContext(Dispatchers.IO) {
        withTimeoutOrNull(9000L) {
            runCatching {
                val cleanId = resolveCleanVideoId(videoId, trackName, artistName)
                    ?: return@runCatching null

                Log.d(tag, "Attempting caption extraction for cleanId=$cleanId ($trackName - $artistName)")
                val tracks = fetchCaptionTracks(cleanId)
                if (tracks.isEmpty()) {
                    Log.d(tag, "No caption tracks found for $cleanId")
                    return@runCatching null
                }

                val bestTrack = selectBestSubtitleTrack(tracks, preferredLanguage)
                    ?: return@runCatching null

                Log.d(
                    tag,
                    "Selected caption track [lang=${bestTrack.languageCode}, auto=${bestTrack.isAutoGenerated}] for $cleanId"
                )

                val rawContent = downloadCaptionContent(bestTrack)
                if (rawContent.isNullOrBlank()) {
                    Log.w(tag, "Downloaded subtitle content was empty for $cleanId")
                    return@runCatching null
                }

                val lrc = CaptionTranscriptParser.parseCaptionsToLrc(rawContent)
                if (lrc.isNullOrBlank() || !CaptionTranscriptParser.isValidLrcTranscript(lrc)) {
                    Log.d(tag, "Parsed caption text was not valid LRC for $cleanId")
                    return@runCatching null
                }

                val plain = CaptionTranscriptParser.stripLrcTags(lrc)
                if (plain.isBlank() || plain.length < 20) return@runCatching null

                val isAuto = bestTrack.isAutoGenerated
                Lyrics(
                    id = "$cleanId|Captions".hashCode(),
                    trackName = trackName,
                    artistName = artistName,
                    plainLyrics = plain,
                    syncedLyrics = lrc,
                    duration = durationSeconds,
                    language = bestTrack.languageCode,
                    source = if (isAuto) "YouTube Captions (Auto)" else "YouTube Captions"
                )
            }.getOrElse { e ->
                Log.w(tag, "Caption extraction failed for $videoId: ${e.message}")
                null
            }
        }
    }

    private fun resolveCleanVideoId(rawId: String?, trackName: String, artistName: String): String? {
        extractCleanVideoId(rawId)?.let { return it }
        val query = "$trackName $artistName".trim()
        if (query.isBlank()) return null
        return searchYouTubeForVideoId(query)
    }

    private fun extractCleanVideoId(rawId: String?): String? {
        if (rawId.isNullOrBlank()) return null
        val stripped = rawId
            .removePrefix("youtube_")
            .substringAfter("v=", rawId.removePrefix("youtube_"))
            .substringBefore("&")
            .trim()
        return stripped.takeIf { it.length in 10..12 && !it.contains(" ") }
    }

    private fun searchYouTubeForVideoId(query: String): String? {
        return runCatching {
            val payload = JsonObject().apply {
                add("context", JsonObject().apply {
                    add("client", JsonObject().apply {
                        addProperty("clientName", "ANDROID")
                        addProperty("clientVersion", "20.22.38")
                        addProperty("osName", "Android")
                        addProperty("osVersion", "14")
                        addProperty("hl", "en")
                        addProperty("gl", "US")
                    })
                })
                addProperty("query", query)
            }

            val request = Request.Builder()
                .url(YT_SEARCH_API)
                .header("User-Agent", ANDROID_USER_AGENT)
                .post(payload.toString().toRequestBody(JSON_MEDIA_TYPE))
                .build()

            client.newCall(request).execute().use { response ->
                if (!response.isSuccessful) return@use null
                val body = response.body?.string() ?: return@use null
                findVideoIdInJson(JsonParser.parseString(body))
            }
        }.getOrNull()
    }

    private fun findVideoIdInJson(element: JsonElement): String? {
        if (element.isJsonObject) {
            val obj = element.asJsonObject
            if (obj.has("videoId") && obj.get("videoId").isJsonPrimitive) {
                val vid = obj.get("videoId").asString
                if (vid.length in 10..12 && !vid.contains(" ")) return vid
            }
            for (entry in obj.entrySet()) {
                val found = findVideoIdInJson(entry.value)
                if (found != null) return found
            }
        } else if (element.isJsonArray) {
            for (item in element.asJsonArray) {
                val found = findVideoIdInJson(item)
                if (found != null) return found
            }
        }
        return null
    }

    internal fun fetchCaptionTracks(cleanId: String): List<CaptionTrackInfo> {
        // Strategy 1: YouTube Android Player endpoint (fast, bypasses desktop bot mitigations)
        fetchCaptionsFromInnerTubePlayer(cleanId, "ANDROID", "20.22.38", ANDROID_USER_AGENT)?.takeIf { it.isNotEmpty() }?.let {
            return it
        }

        // Strategy 2: YouTube iOS Player endpoint
        fetchCaptionsFromInnerTubePlayer(cleanId, "IOS", "20.22.3", IOS_USER_AGENT)?.takeIf { it.isNotEmpty() }?.let {
            return it
        }

        // Strategy 3: Check cached NewPipe StreamInfo if already resolved during playback
        StreamResolver.getCachedStreamInfo(cleanId)?.subtitles?.takeIf { it.isNotEmpty() }?.let { subs ->
            return subs.map { it.toCaptionTrackInfo() }
        }

        // Strategy 4: Fallback to NewPipe StreamInfo fetch
        return runCatching {
            YouTubeMusicExtractor.getInstance()
            val url = "https://www.youtube.com/watch?v=$cleanId"
            val info = StreamInfo.getInfo(ServiceList.YouTube, url)
            info.subtitles.orEmpty().map { it.toCaptionTrackInfo() }
        }.getOrDefault(emptyList())
    }

    private fun fetchCaptionsFromInnerTubePlayer(
        cleanId: String,
        clientName: String,
        clientVersion: String,
        userAgent: String
    ): List<CaptionTrackInfo>? = runCatching {
        val payload = JsonObject().apply {
            add("context", JsonObject().apply {
                add("client", JsonObject().apply {
                    addProperty("clientName", clientName)
                    addProperty("clientVersion", clientVersion)
                    addProperty("hl", "en")
                    addProperty("gl", "US")
                    if (clientName == "ANDROID") {
                        addProperty("osName", "Android")
                        addProperty("osVersion", "14")
                    } else if (clientName == "IOS") {
                        addProperty("deviceMake", "Apple")
                        addProperty("deviceModel", "iPhone16,2")
                        addProperty("osName", "iOS")
                        addProperty("osVersion", "18.5.0.22F76")
                    }
                })
            })
            addProperty("videoId", cleanId)
        }

        val request = Request.Builder()
            .url(YT_PLAYER_API)
            .header("User-Agent", userAgent)
            .post(payload.toString().toRequestBody(JSON_MEDIA_TYPE))
            .build()

        client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) return@use null
            val body = response.body?.string() ?: return@use null
            val root = JsonParser.parseString(body).asJsonObject
            val captionsObj = if (root.has("captions") && root.get("captions").isJsonObject) {
                root.getAsJsonObject("captions")
            } else null ?: return@use null

            val tracklist = if (captionsObj.has("playerCaptionsTracklistRenderer") && captionsObj.get("playerCaptionsTracklistRenderer").isJsonObject) {
                captionsObj.getAsJsonObject("playerCaptionsTracklistRenderer")
            } else null ?: return@use null

            val captionTracks = if (tracklist.has("captionTracks") && tracklist.get("captionTracks").isJsonArray) {
                tracklist.getAsJsonArray("captionTracks")
            } else null ?: return@use null

            val resultList = mutableListOf<CaptionTrackInfo>()
            for (elem in captionTracks) {
                if (!elem.isJsonObject) continue
                val track = elem.asJsonObject
                val baseUrlElem = track.get("baseUrl") ?: continue
                if (!baseUrlElem.isJsonPrimitive) continue
                val baseUrl = baseUrlElem.asString
                val lang = if (track.has("languageCode") && track.get("languageCode").isJsonPrimitive) {
                    track.get("languageCode").asString
                } else ""
                val nameObj = if (track.has("name") && track.get("name").isJsonObject) {
                    track.getAsJsonObject("name")
                } else null
                val name = if (nameObj != null && nameObj.has("simpleText") && nameObj.get("simpleText").isJsonPrimitive) {
                    nameObj.get("simpleText").asString
                } else lang
                val kind = if (track.has("kind") && track.get("kind").isJsonPrimitive) {
                    track.get("kind").asString
                } else ""
                val vssId = if (track.has("vssId") && track.get("vssId").isJsonPrimitive) {
                    track.get("vssId").asString
                } else ""
                val isAuto = kind.equals("asr", ignoreCase = true) || vssId.startsWith("a.")
                resultList.add(
                    CaptionTrackInfo(
                        url = baseUrl,
                        languageCode = lang,
                        name = name,
                        isAutoGenerated = isAuto
                    )
                )
            }
            resultList.toList()
        }
    }.getOrNull()

    private fun SubtitlesStream.toCaptionTrackInfo(): CaptionTrackInfo {
        return CaptionTrackInfo(
            url = url.orEmpty(),
            languageCode = languageTag.orEmpty(),
            name = languageTag.orEmpty(),
            isAutoGenerated = isAutoGenerated,
            content = content
        )
    }

    internal fun selectBestSubtitleTrack(
        tracks: List<CaptionTrackInfo>,
        preferredLanguage: String?
    ): CaptionTrackInfo? {
        val preferred = preferredLanguage?.lowercase()?.trim()?.takeIf { it.isNotBlank() }

        // 1. Human-uploaded matching preferred language
        if (preferred != null) {
            tracks.firstOrNull {
                !it.isAutoGenerated && it.languageCode.equals(preferred, ignoreCase = true)
            }?.let { return it }
        }

        // 2. Human-uploaded English
        tracks.firstOrNull {
            !it.isAutoGenerated && it.languageCode.startsWith("en", ignoreCase = true)
        }?.let { return it }

        // 3. Human-uploaded any language
        tracks.firstOrNull { !it.isAutoGenerated }?.let { return it }

        // 4. Auto-generated matching preferred language
        if (preferred != null) {
            tracks.firstOrNull {
                it.isAutoGenerated && it.languageCode.equals(preferred, ignoreCase = true)
            }?.let { return it }
        }

        // 5. Auto-generated English
        tracks.firstOrNull {
            it.isAutoGenerated && it.languageCode.startsWith("en", ignoreCase = true)
        }?.let { return it }

        // 6. First available
        return tracks.firstOrNull()
    }

    private fun downloadCaptionContent(track: CaptionTrackInfo): String? {
        if (!track.content.isNullOrBlank()) {
            return track.content
        }
        val url = track.url
        if (url.isBlank()) return null

        val uas = listOf(
            ANDROID_USER_AGENT,
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/136.0.0.0 Safari/537.36"
        )

        for (ua in uas) {
            val request = Request.Builder()
                .url(url)
                .header("User-Agent", ua)
                .build()

            val content = runCatching {
                client.newCall(request).execute().use { response ->
                    if (response.isSuccessful) response.body?.string() else null
                }
            }.getOrNull()

            if (!content.isNullOrBlank()) {
                return content
            }
        }
        return null
    }

    internal fun parseCaptionsToLrc(raw: String): String? = CaptionTranscriptParser.parseCaptionsToLrc(raw)

    companion object {
        private const val YT_PLAYER_API = "https://www.youtube.com/youtubei/v1/player?key=AIzaSyAO_FJ2SlqU8Q4STvLGLRnjIzNdFu-5C38"
        private const val YT_SEARCH_API = "https://www.youtube.com/youtubei/v1/search?key=AIzaSyAO_FJ2SlqU8Q4STvLGLRnjIzNdFu-5C38"
        private const val ANDROID_USER_AGENT = "com.google.android.youtube/20.22.38 (Linux; U; Android 14) gzip"
        private const val IOS_USER_AGENT = "com.google.ios.youtube/20.22.3 (iPhone16,2; U; CPU iOS 18_5 like Mac OS X;)"
        private val JSON_MEDIA_TYPE = "application/json; charset=utf-8".toMediaType()
    }
}
